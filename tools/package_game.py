class EntryAssets(HTMLParser):
    def __init__(self):
        super().__init__()
        self.paths = set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'script' and 'src' in attrs:
            self.paths.add(attrs['src'])
        if tag == 'link' and attrs.get('rel') == 'stylesheet':
            self.paths.add(attrs['href'])


def runtime_files():
    assets = EntryAssets()
    assets.feed((ROOT / 'index.html').read_text(encoding='utf-8'))
    files = {'index.html', 'README.md', 'UPDATE-1.5.txt', 'UPDATE-1.4.3.txt', 'UPDATE-1.4.2.txt', 'docs/clip-times.md', 'docs/national-vehicles.tsv', 'assets/depot-entry.webp', 'vendor/three.LICENSE', 'vendor/supabase-auth.LICENSE', 'vendor/realtime.LICENSE', 'vendor/tslib.LICENSE'} | assets.paths
    files.update(p.relative_to(ROOT).as_posix() for p in (ROOT / 'assets/flags').glob('*.webp'))
    for sector in ('city','field','desert','port','quarry','frost','burgstadt','cape','sawmill','airfield'):
        files.add(f'assets/sectors/{sector}.webp')
    files.add('assets/ornaments/winter-yard.svg')
    files.update(f'assets/ornaments/{toy}.webp' for toy in ('gingerbread', 'deer', 'fir', 'bauble'))
    countries = ('ussr', 'germany', 'france', 'sweden', 'usa', 'japan')
    for crate in ('basic', 'premium', 'collection', 'ornament', *(f'national-{c}' for c in countries)):
        for pose in ('', '-open', '-motion'):
            files.add(f'assets/crates/{crate}{pose}.webp')
    for model in (ROOT / 'models').glob('*.mesh.js'):
        files.add('models/' + model.name)
        files.add('models/' + model.name.removesuffix('.mesh.js') + '.webp')
    return sorted(files)


if __name__ == '__main__':
    files = runtime_files()
    for name in files:
        if not (ROOT / name).is_file() or not (ROOT / name).resolve().is_relative_to(ROOT):
            raise ValueError(f'Invalid runtime asset: {name}')
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'CITY-TANKS.zip',
                        help='Write a separate local build without replacing CITY-TANKS.zip')
    output = parser.parse_args().output
    output.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(output, 'w', compression=ZIP_DEFLATED, compresslevel=9) as z:
        for name in files:
            z.write(ROOT / name, name)
        z.writestr('СТАРТ.txt', START)
    with ZipFile(output) as z:
        assert z.testzip() is None
    print(f'{output.name}: {len(files)+1} files · {output.stat().st_size:,} bytes')
