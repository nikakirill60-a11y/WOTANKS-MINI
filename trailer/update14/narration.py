def cue_start(name, i):
    take = TAKES[name]
    return take.at + take.cues[i][0]


def captions():
    return [(take.at + a, take.at + b, words.strip())
            for take in TAKES.values() for a, b, words in take.cues]


def verify_sources(end):
    last = 0
    for key, take in TAKES.items():
        if sha256(take.path.read_bytes()).hexdigest() != take.sha256:
            raise ValueError(f'Not the selected {VOICE_ID} recording: {take.file}')
        assert last <= take.at < take.at + take.duration <= end, key
        last = take.at + take.duration
        prev = 0
        for a, b, words in take.cues:
            assert prev <= a < b <= take.duration and words.strip(), (key, a, b)
            prev = b
